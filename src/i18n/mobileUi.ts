function detectedRuntimeLocale(): string | undefined {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale;
  } catch {
    return undefined;
  }
}

let activeMobileLocale: Locale = resolveLocale(detectedRuntimeLocale());

export function setMobileUiLocale(locale?: string): void {
  activeMobileLocale = resolveLocale(locale ?? detectedRuntimeLocale());
}

export function mobileT(key: string, vars?: Record<string, string | number>): string {
  return translate(MOBILE_UI_COPY, key, activeMobileLocale, vars);
}
